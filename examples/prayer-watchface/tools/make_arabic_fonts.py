"""Generate BMFont bitmap fonts with Arabic-Indic digits (U+0660..U+0669) and ':' for the watch.

The FR55 system number fonts have no Arabic digits, so the clock and prayer times use these.
Also writes source/ArabicText.mc: prayer names and "time left" already shaped (joined letter
forms), because the watch cannot shape Arabic. They stay in logical order: the watch text
engine does the right-to-left reordering itself (checked in the simulator).
Usage: uv run --no-project --with pillow --with arabic-reshaper \
         python tools/make_arabic_fonts.py [path/to/font.ttf]
Default font: Noto Sans Arabic Bold (SIL Open Font License, see tools/fonts/OFL.txt).
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import arabic_reshaper

TTF = sys.argv[1] if len(sys.argv) > 1 else str(Path(__file__).resolve().parent / "fonts" / "NotoSansArabic-Bold.ttf")
OUT = Path(__file__).resolve().parent.parent / "resources" / "fonts"
DIGITS = [chr(c) for c in range(0x0660, 0x066A)] + [":", " "]
# Fajr, Dhuhr, Asr, Maghrib, Isha, "time left", sunrise, dhuha
WORDS = ["الفجر", "الظهر", "العصر", "المغرب", "العشاء", "متبقي", "الشروق", "الضحى"]
VISUAL = [arabic_reshaper.reshape(w) for w in WORDS]
TEXT_CHARS = DIGITS + sorted(set("".join(VISUAL)))

# (resource name, pixel size, extra stroke for weight, chars): big ~FONT_NUMBER_HOT, small ~FONT_XTINY,
# text ~FONT_SMALL for the prayer-name line
SIZES = [("ar_big", 46, 2, DIGITS), ("ar_small", 17, 0, DIGITS), ("ar_text", 21, 0, TEXT_CHARS)]


def build(name: str, size: int, stroke: int, chars: list) -> None:
    font = ImageFont.truetype(TTF, size)
    ascent, descent = font.getmetrics()
    line_h = ascent + descent
    pad = 2
    cells = []
    x = 0
    for ch in chars:
        left, top, right, bottom = font.getbbox(ch, stroke_width=stroke)
        w = max(right - left, 1)
        h = max(bottom - top, 1)
        cells.append((ch, x, left, top, w, h, round(font.getlength(ch)) + 2 * stroke))
        x += w + pad
    # tight line box around the real glyphs: Noto's ascent/descent are very tall, which would
    # push VCENTER-aligned text far off position on the watch
    inked = [c for c in cells if c[0] != " "]
    min_top = min(c[3] for c in inked)
    line_h = max(c[3] + c[5] for c in inked) - min_top + 2
    sheet = Image.new("RGBA", (x, max(c[5] for c in cells)), (0, 0, 0, 0))
    for ch, cx, left, top, w, h, adv in cells:
        # draw in a 1-bit mask (MIP screen, no anti-aliasing), then paste as opaque white
        mask = Image.new("L", (w, h), 0)
        ImageDraw.Draw(mask).text((-left, -top), ch, font=font, fill=255, stroke_width=stroke, stroke_fill=255)
        mask = mask.point(lambda v: 255 if v >= 128 else 0)
        sheet.paste((255, 255, 255, 255), (cx, 0), mask)
    sheet.save(OUT / f"{name}.png")

    lines = [
        f'info face="{name}" size={size} bold=1 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0',
        f"common lineHeight={line_h} base={ascent - min_top + 1} scaleW={sheet.width} scaleH={sheet.height} pages=1 packed=0",
        f'page id=0 file="{name}.png"',
        f"chars count={len(cells)}",
    ]
    for ch, cx, left, top, w, h, adv in cells:
        lines.append(
            f"char id={ord(ch)} x={cx} y=0 width={w} height={h} xoffset={left} yoffset={top - min_top + 1} "
            f"xadvance={adv} page=0 chnl=15"
        )
    (OUT / f"{name}.fnt").write_text("\n".join(lines) + "\n")
    # self-check: every digit actually has ink
    alpha = sheet.getchannel("A")
    for ch, cx, left, top, w, h, adv in cells[:10]:
        assert alpha.crop((cx, 0, cx + w, h)).getbbox(), f"empty glyph {ch!r} in {name}"
    print(f"{name}: {sheet.width}x{sheet.height}, line {line_h}px")


OUT.mkdir(parents=True, exist_ok=True)
for n, s, k, c in SIZES:
    build(n, s, k, c)
(OUT / "fonts.xml").write_text(
    "<fonts>\n"
    + "".join(f'    <font id="{n.title().replace("_", "")}" filename="{n}.fnt" antialias="false"/>\n' for n, _, _, _ in SIZES)
    + "</fonts>\n"
)

src = Path(__file__).resolve().parent.parent / "source" / "ArabicText.mc"
names = ", ".join(f'"{v}"' for v in VISUAL[:5])
src.write_text(
    "// Generated by tools/make_arabic_fonts.py - shaped Arabic, logical order. Do not edit.\n"
    "import Toybox.Lang;\n\nmodule ArabicText {\n"
    f"    const NAMES = [{names}] as Array<String>;\n"
    f'    const LEFT = "{VISUAL[5]}";\n'
    f'    const SUNRISE = "{VISUAL[6]}";\n'
    f'    const DHUHA = "{VISUAL[7]}";\n'
    "}\n"
)
print("wrote", src)
